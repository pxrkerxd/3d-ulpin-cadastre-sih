def segment_building(total_height, base_elevation=0, floor_height=3.2, archetype=None, property_type=None, property_name=None):
    """
    Slices a property into individual 3D volumetric units/floors with authentic,
    landmark-specific floor nomenclature and architectural designations, including unique owners.
    """
    if isinstance(floor_height, str):
        # Handle case where archetype was passed as 3rd positional argument
        archetype = floor_height
        floor_height = 3.2

    try:
        floor_height = float(floor_height)
    except (ValueError, TypeError):
        floor_height = 3.2

    profile = ARCHETYPE_FLOOR_PROFILES.get(archetype)
    is_res = (property_type and "Apartment" in property_type) or (property_name and "Residency" in property_name)
    
    # Calculate number of slices needed
    effective_h = abs(float(total_height))
    calculated_slices = max(1, int(round(effective_h / floor_height)))

    floors = []
    
    if base_elevation < 0:
        # Subsurface / Underground property
        b_list = profile.get('basements') if profile else None
        num_basements = min(len(b_list), calculated_slices) if b_list else min(calculated_slices, 5)
        step = abs(float(base_elevation)) / max(1, num_basements)
        
        for i in range(num_basements):
            f_num = -(i + 1)
            z_s = base_elevation + (i * step)
            z_e = z_s + step
            
            if b_list and i < len(b_list):
                item = b_list[i]
                code, name, stratum, use = item[:4]
                flr_owner = item[4] if len(item) > 4 else "Subsurface Infrastructure SPV"
            else:
                code = f"B0{i+1}"
                name = f"Subsurface Level {i+1} - Infrastructure & Parking"
                stratum = "SUB"
                use = "Subsurface Infrastructure"
                flr_owner = f"Subsurface Infrastructure Authority (Level {i+1})"
                
            floors.append({
                'floor_number': f_num,
                'z_start': round(z_s, 2),
                'z_end': round(z_e, 2),
                'base_elevation': round(min(z_s, z_e), 2),
                'top_elevation': round(max(z_s, z_e), 2),
                'level_code': code,
                'floor_name': name,
                'stratum_type': stratum,
                'use_category': use,
                'owner': flr_owner
            })
    else:
        # Above-ground / Mixed superstructure
        b_list = profile.get('basements', []) if profile else []
        s_list = profile.get('superstructure', []) if profile else []
        
        # Add 1-2 subsurface basements if applicable
        num_sub = min(2, len(b_list)) if b_list else 0
        for bi in range(num_sub):
            f_num = -(num_sub - bi)
            z_s = -((num_sub - bi) * 3.5)
            z_e = z_s + 3.5
            item = b_list[bi]
            code, name, stratum, use = item[:4]
            flr_owner = item[4] if len(item) > 4 else "Subsurface Parking & Facility SPV"
            floors.append({
                'floor_number': f_num,
                'z_start': round(z_s, 2),
                'z_end': round(z_e, 2),
                'base_elevation': round(min(z_s, z_e), 2),
                'top_elevation': round(max(z_s, z_e), 2),
                'level_code': code,
                'floor_name': name,
                'stratum_type': stratum,
                'use_category': use,
                'owner': flr_owner
            })
            
        # Add superstructure floors
        num_super = max(1, calculated_slices)
        for i in range(num_super):
            f_num = i + 1
            z_s = base_elevation + (i * floor_height)
            z_e = z_s + floor_height
            
            if s_list and i < len(s_list):
                item = s_list[i]
                code, name, stratum, use = item[:4]
                flr_owner = item[4] if len(item) > 4 else (DIVERSE_RESIDENT_OWNERS[i % len(DIVERSE_RESIDENT_OWNERS)] if is_res else f"{property_name or 'Commercial'} Unit #{i+1}")
            elif i == 0:
                code = "G00"
                name = f"Ground Floor - Grand Reception & Visitor Atrium"
                stratum = "COM"
                use = "Lobby & Reception"
                flr_owner = f"{property_name or 'Property'} Reception & Facilities Trust"
            elif i == num_super - 1:
                code = f"L{i:02d}"
                name = f"Penthouse Crown & Observation Sky Deck"
                stratum = "AIR"
                use = "Observation / Air Rights"
                flr_owner = f"Crown Penthouse Executive Titleholder"
            else:
                code = f"L{i:02d}"
                name = f"Level {i:02d} - Premium Floor Units ({property_type or 'Commercial'})"
                stratum = "BLD"
                use = property_type or "Commercial"
                flr_owner = DIVERSE_RESIDENT_OWNERS[i % len(DIVERSE_RESIDENT_OWNERS)] if is_res else f"Enterprise Corporate Leaseholder (Level {i:02d})"
                
            floors.append({
                'floor_number': f_num,
                'z_start': round(z_s, 2),
                'z_end': round(z_e, 2),
                'base_elevation': round(min(z_s, z_e), 2),
                'top_elevation': round(max(z_s, z_e), 2),
                'level_code': code,
                'floor_name': name,
                'stratum_type': stratum,
                'use_category': use,
                'owner': flr_owner
            })
            
    return floors

def get_floor_display_label(floor_dict):
    """
    Returns a clean, descriptive single-line label for UI selectors.
    e.g. 'Level 04: Signature Sea-Facing Luxury Residences (+12.8m to +16.0m)'
    """
    code = floor_dict.get('level_code', f"F{abs(floor_dict.get('floor_number', 1)):02d}")
    name = floor_dict.get('floor_name', 'Volumetric Spatial Unit')
    z_bot = floor_dict.get('base_elevation', floor_dict.get('z_start', 0))
    z_top = floor_dict.get('top_elevation', floor_dict.get('z_end', 0))
    
    z_str = f"{z_bot:+.1f}m to {z_top:+.1f}m"
    return f"{code} • {name} ({z_str})"